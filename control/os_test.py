import opensim as osim
m=osim.Model(); m.setName('one_muscle')
body=osim.Body('b',1.0,osim.Vec3(0),osim.Inertia(0.1,0.1,0.1,0,0,0)); m.addBody(body)
j=osim.PinJoint('j',m.getGround(),osim.Vec3(0),osim.Vec3(0),body,osim.Vec3(0,0.5,0),osim.Vec3(0)); m.addJoint(j)
mus=osim.Thelen2003Muscle('m',200.0,0.1,0.1,0.0)
mus.addNewPathPoint('p1',m.getGround(),osim.Vec3(0.1,0,0))
mus.addNewPathPoint('p2',body,osim.Vec3(0,0,0))
m.addForce(mus)
ctrl=osim.PrescribedController(); ctrl.addActuator(mus)
ctrl.prescribeControlForActuator('m',osim.Constant(0.85)); m.addController(ctrl)
s=m.initSystem(); s.setTime(0.0)
mgr=osim.Manager(m); mgr.initialize(s); s=mgr.integrate(0.5)
print('OPENSIM_VERSION',osim.__version__)
print('MUSCLE_ACTIVATION_at_0.5s',round(mus.getActivation(s),4))
print('MUSCLE_FORCE',round(mus.getActuation(s),3))
print('OPENSIM_OK')
